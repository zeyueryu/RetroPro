package com.retropro.util

import java.time.LocalDate

/**
 * 每日格言 —— 记录页左上角的一句话。
 *
 * ## 两条路径
 *
 *  - **预设**：内置格言库按日期确定性轮换（dayOfYear 对库长取模），
 *    同一天内稳定、跨天自动换，不依赖任何存储。
 *  - **自定义**：用户在「我的 → 每日格言」设一句自己的（存 SharedPreferences，
 *    由 [AppPrefs.Live.dailyQuote] 提供），设了就固定显示这句；清空回到轮换。
 *
 * 判定收在 [forToday] 一处，读取方只调它，不各自抄逻辑。
 */
object DailyQuotes {

    /** 预设库：原创短句，围绕"每一拍都算数"的复盘精神 */
    val PRESETS: List<String> = listOf(
        "每一拍都算数。",
        "输的球不白输，前提是你回头看。",
        "今天多想一拍，比赛少丢一分。",
        "手感会骗人，记录不会。",
        "把失误写下来，它就不敢再来。",
        "输球不可怕，可怕的是不知道为什么输。",
        "练球如存钱，比赛才敢花。",
        "别赶着赢，先赶着不丢。",
        "看不清的球，往往是脚步先慢了。",
        "稳一拍，再稳一拍，节奏就回来了。",
        "复盘不是认错，是找便宜。",
        "对手的强，是你进步的坐标。",
        "今天流的汗，是明天底气的利息。",
        "球不会说谎，你会——所以记下来。",
        "落后时先赢回一拍，再赢回一局。",
        "赢在变招，输在恋战。",
        "多一拍回位，少一分遗憾。",
        "动作可以练，习惯只能养。",
        "球场上没有白费的努力，只有没记下的教训。",
        "发球线前想清楚，比中场救火强。",
        "输给强手是学费，输给自己是欠账。",
        "每个球都是新的一分，每局都是新的开始。",
        "练什么，赛场上就敢用什么。",
        "手腕松一点，脑子紧一点。",
        "打得久，比打得狠更难。",
        "别盯记分牌，盯下一拍。",
        "今天最想赢的，是昨天的自己。",
        "球要打，账要记，日子才有回甘。",
    )

    /** 今天该显示哪句：自定义优先（非空白），否则按日轮换。判定唯一收口 */
    fun forToday(custom: String?): String =
        custom?.takeIf { it.isNotBlank() } ?: PRESETS[LocalDate.now().dayOfYear % PRESETS.size]

    /** 今天轮换到的是库里的第几条（下标）；设置页高亮用 */
    fun todayPresetIndex(): Int = LocalDate.now().dayOfYear % PRESETS.size
}
